def is_json_file_empty(file_path):
    # 检查文件是否存在
    if not os.path.exists(file_path):
        print(f"文件不存在: {file_path}")
        return True  # 或根据需求返回False
    
    # 检查文件大小是否为0（无任何内容）
    if os.path.getsize(file_path) == 0:
        return True
    
    # 检查文件内容是否全为空白字符（空格、换行等）
    with open(file_path, "r", encoding="utf-8") as f:
        content = f.read().strip()  # 去除首尾空白
        return len(content) == 0

def compare_entities_with_protocols(entities, protocols):
    prompt = """You are an expert in experimental protocol evaluation for Fischer–Tropsch synthesis.
You will be given:

1. A **list of target experimental entities** (from one chapter of a protocol template).
2. **5 experimental protocols** generated by different methods.

Your task is to evaluate, **for each entity**, whether it is **covered** in each of the 5 protocols.

---

### **Input Entities (Target Chapter):**

{entities_json}

### **Input Protocols:**

Protocol 1: {summary_1}
Protocol 2: {summary_2}
Protocol 3: {summary_3}
Protocol 4: {summary_4}
Protocol 5: {summary_5}

---

### **Coverage Definition (Binary: covered / absent):**

* **Covered**:

  * The entity is explicitly mentioned OR represented by a synonym, abbreviation, or functional equivalent.
  * Use semantic understanding (e.g., "HCl" covers "hydrochloric acid", "CTAB" covers "cetyltrimethylammonium bromide").
* **Absent**:

  * The entity is not present, or its presence cannot be confidently inferred.

#### **Boundary Rules (Critical for correct classification):**

* Classify by **function & context**, not just name matches.
* **Passivation Atmosphere Gases**: Must be clearly linked to passivation; purge or DRIFTS carrier gases do not count.
* **Synthesis Gas Environment Gases**: Only counts if used as reaction feed gas, not for reduction/carburization/characterization.
* **Solvents vs Other Reagents**: Solvents = dissolving/washing/dispersing; Other Reagents = participate in reactions.
* **Equipment**: Assign to Activation, Reaction, or Synthesis based on explicit stage/purpose (e.g., "tube furnace for reduction" = Activation Equipment).
* **Negation Rules**: If context explicitly shows non-relevant use (e.g., "Ar as purge gas only"), mark **absent**.

---

### **Output Requirements (Strict JSON):**

Return **only** a JSON object in this structure:

```
{
"EntityName1": {
"Protocol1": "covered/absent",
"Protocol2": "covered/absent",
"Protocol3": "covered/absent",
"Protocol4": "covered/absent",
"Protocol5": "covered/absent"
},
"EntityName2": {
...
}
}
```

#### **Optional Traceability (Do not mix with main JSON):**

If possible, maintain an internal record of:

* **evidence**: Short text supporting the decision.
* **confidence**: high / medium / low (based on explicitness of mention).

But **output only the main JSON** above.

---

### **Evaluation Mode:**

* Apply synonyms, abbreviations, and functionally equivalent terms.
* Apply boundary and negation rules strictly.
* Default to **absent** unless coverage is clearly supported."""\
    .replace("{entities_json}",json.dumps(entities, ensure_ascii=False, indent=2))\
    .replace("{summary_1}",protocols[0])\
    .replace("{summary_2}",protocols[1])\
    .replace("{summary_3}",protocols[2])\
    .replace("{summary_4}",protocols[3])\
    .replace("{summary_5}",protocols[4])\
    # .replace("{summary_6}",protocols[5])
    # print(prompt)
    
    llm = ChatOpenAI(model="gpt-4o-mini", temperature=0)
    # llm = ChatOpenAI(model="gpt-4.1-nano", temperature=0)
    response = llm.predict(prompt)

    # return response.replace("```json", "").replace("```", "").strip()
    return json.loads(response.replace("```json", "").replace("```", "").strip())
