def check_paper_id_exists(data: list[list[dict]], paper_id: int) -> bool:
    """检查指定的paper_id是否存在于嵌套列表结构的JSON数据中"""
    # 遍历外层列表
    for paper_data in data:
        if paper_data.get("paper_id") == paper_id:
            return True
    return False

